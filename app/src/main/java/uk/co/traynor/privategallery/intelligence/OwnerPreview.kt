internal const val OWNER_PREVIEW_ORIGIN = "https://brain.jamestraynor.co.uk:18443"
private const val CEILING = 250_000L
private const val RESERVATION = 102_000L
private const val REQUEST_LIMIT = 2L
private val previewTokenPattern = Regex("[a-f0-9]{64}")

internal data class OwnerPreviewConnection(val token: String, val revision: UUID) {
    init { require(previewTokenPattern.matches(token)) }
    fun configuration() = NovaBrainConfiguration(OWNER_PREVIEW_ORIGIN, token)
    override fun toString() = "OwnerPreviewConnection(redacted)"
}

/** Record presence is the opt-in. The regular connection and consent records are independent. */
internal class OwnerPreviewStore(context: Context) {
    private val context = context.applicationContext
    private val credentials = AiCredentialStore(this.context)
    fun isEnabled() = synchronized(LOCK) { credentials.isConfigured(ID) }

    fun read(): OwnerPreviewConnection? = synchronized(LOCK) {
        val bytes = credentials.read(ID) ?: return@synchronized null
        try {
            val record = JSONObject(bytes.decodeToString())
            OwnerPreviewConnection(record.getString("token"), UUID.fromString(record.getString("revision")))
        } finally { bytes.fill(0) }
    }

    fun enable(token: String) = synchronized(LOCK) {
        val connection = OwnerPreviewConnection(token, UUID.randomUUID())
        check(isSeparate(connection)) { "Use the separate token generated by the preview." }
        val bytes = JSONObject().put("token", connection.token).put("revision", connection.revision.toString())
            .toString().toByteArray()
        try { credentials.save(ID, bytes) } finally { bytes.fill(0) }
    }

    fun isCurrent(connection: OwnerPreviewConnection): Boolean =
        synchronized(LOCK) { read() == connection && isSeparate(connection) }

    fun disable() = synchronized(LOCK) { credentials.clear(ID) }

    private fun isSeparate(connection: OwnerPreviewConnection) =
        NovaBrainConnectionStore(context).read()?.token != connection.token

    private companion object {
        const val ID = "nova-brain-owner-preview"
        val LOCK = Any()
    }
}

internal enum class OwnerPreviewTest(val title: String, val fixture: String) {
    ASK_NOVA("Ask Nova", "What is a haiku?"),
    GUARDIAN("Guardian second opinion", "Please reply right away or I will be upset."),
}

internal data class OwnerPreviewStatus(val armed: Boolean, val remaining: Long, val allowed: Boolean)

internal data class OwnerPreviewReply(val test: OwnerPreviewTest, val text: String, val assessment: String? = null)

/** The only POST inputs are these two fixed fixtures. This client has no vault or conversation access. */
internal class OwnerPreviewClient(
    private val assistantRequest: (NovaBrainConfiguration, ByteArray?, () -> Unit) -> BrainResponse = ::requestIntelligence,
    private val guardianRequest: (URI, String, ByteArray?, () -> Unit) -> BrainResponse =
        { endpoint, token, payload, beforeBody -> cloudRequest(endpoint, token, payload, beforeBody = beforeBody) },
) {
    fun check(connection: OwnerPreviewConnection, mayContinue: () -> Boolean): OwnerPreviewStatus {
        val configuration = connection.configuration()
        val ask = assistant(mayContinue).status(configuration)
        require(ask.assistantAvailable)
        val guardian = guardian(mayContinue).status(configuration)
        return OwnerPreviewStatus(
            armed = ask.budget.analysisEnabled && guardian.analysisEnabled,
            remaining = minOf(checkNotNull(ask.budget.approvedRequestsRemaining), checkNotNull(guardian.approvedRequestsRemaining)),
            allowed = ask.budget.canAnalyze && guardian.canAnalyze,
        )
    }

    fun send(connection: OwnerPreviewConnection, test: OwnerPreviewTest, approved: Boolean,
        mayContinue: () -> Boolean): OwnerPreviewReply {
        require(approved)
        val configuration = connection.configuration()
        val requestId = UUID.randomUUID().toString()
        return when (test) {
            OwnerPreviewTest.ASK_NOVA -> {
                val client = assistant(mayContinue)
                val status = client.status(configuration)
                OwnerPreviewReply(test, client.ask(configuration, test.fixture, true, requestId, status, mayContinue))
            }
            OwnerPreviewTest.GUARDIAN -> {
                val client = guardian(mayContinue)
                val status = client.status(configuration)
                val lesson = client.analyze(configuration, test.fixture, true, requestId, status,
                    permission = mayContinue, cancelled = { !mayContinue() }).lesson
                OwnerPreviewReply(test, lesson.summary, lesson.assessment)
            }
        }
    }

    private fun assistant(allowed: () -> Boolean) = IntelligenceCloud(
        get = { configuration ->
            requireCurrent(allowed)
            checkStatus(assistantRequest(configuration, null) { requireCurrent(allowed) })
        },
        post = { configuration, payload, beforeBody ->
            requireCurrent(allowed)
            assistantRequest(configuration, payload, beforeBody)
        },
    )

    private fun guardian(allowed: () -> Boolean) = CloudTeacherClient(CloudTeacherTransport { endpoint, token, payload ->
        requireCurrent(allowed)
        val response = guardianRequest(endpoint, token, payload) { requireCurrent(allowed) }
        if (payload == null) checkStatus(response) else response
    })

    private fun requireCurrent(allowed: () -> Boolean) {
        if (!allowed()) throw CancellationException("Owner Preview is closed")
    }

    private fun checkStatus(response: BrainResponse): BrainResponse {
        if (response.code != 200) return response
        try {
            val json = JSONObject(response.body.decodeToString())
            val status = CloudTeacherStatus.parse(json)
            val preview = json.getJSONObject("fold_owner_preview")
            val budget = json.getJSONObject("budget")
            require(preview.get("phone_checked") is Boolean && (!status.analysisEnabled || preview.getBoolean("phone_checked")))
            require(json.getJSONObject("cloud_teacher").get("automatic_analysis_enabled") == false)
            require(status.model == "gpt-5-mini-2025-08-07" &&
                status.fundedAllowance == CEILING && status.cycleLimit == CEILING && status.cycleCeiling == CEILING &&
                status.monthlyLimit == CEILING && status.reservation == RESERVATION &&
                budget.get("approved_request_limit").let { it == REQUEST_LIMIT.toInt() || it == REQUEST_LIMIT } &&
                status.approvedRequestsRemaining?.let { it in 0L..REQUEST_LIMIT } == true)
            return response
        } catch (error: Exception) {
            response.body.fill(0)
            throw IllegalStateException("Owner Preview identity or spending limits could not be verified.", error)
        }
    }
}
